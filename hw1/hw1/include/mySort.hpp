// mySort.hpp
// Собственная сортировка слиянием (merge sort) с интерфейсом как у std::sort.
//
// Идея алгоритма:
//   1. Если элементов мало (<= 16) — сортируем простой сортировкой вставками.
//   2. Иначе делим диапазон пополам, рекурсивно сортируем каждую половину,
//      затем СЛИВАЕМ две отсортированные половины в одну отсортированную.
// Сложность: O(n log n) в ЛЮБОМ случае (в отличие от quicksort, у которого худший случай O(n²)).
// Память: один временный буфер на n/2 элементов.
// Сортировка устойчивая (stable): равные элементы сохраняют исходный взаимный порядок.
//
// Требования к типу элемента T = value_type итератора:
//   * его можно перемещать/присваивать (std::move);
//   * он конструируется по умолчанию (нужно для временного буфера std::vector<T>).
// Требования к итератору: произвольного доступа (random access): it + k, it - it, it < it.
//   Подходят итераторы std::vector, std::deque, std::array и обычные указатели на массив (int*).
//   Не подходят std::list и std::set (у них нет операции «прыгнуть на k шагов»).

#pragma once  // не включать этот файл дважды

#include <cstddef>     // std::size_t — беззнаковый целый тип для размеров/индексов
#include <functional>  // std::less — стандартный компаратор «a < b»
#include <iterator>    // std::iterator_traits — по типу итератора узнать тип элемента
#include <utility>     // std::move — «разрешить забрать значение вместо копирования»
#include <vector>      // std::vector — временный буфер для слияния

// Всё вспомогательное прячем в namespace detail: это «внутренности», пользователь их не вызывает.
// namespace — просто префикс имён, чтобы не было конфликтов (как модуль в Python).
namespace detail {

// Порог, ниже которого рекурсия не нужна: на коротких кусках сортировка вставками быстрее,
// потому что у неё мала константа (нет рекурсивных вызовов и буфера). 16 — типичное значение.
// inline constexpr — константа времени компиляции, безопасная для включения из многих .cpp.
inline constexpr int kInsertionCutoff = 16;

// ---------------------------------------------------------------------------
// Сортировка вставками для диапазона [first, last).
// Как «разложить карты в руке»: берём очередной элемент и сдвигаем его влево,
// пока слева стоит элемент, который должен идти позже.
// Compare& comp — компаратор берём по ссылке, чтобы не копировать его на каждом вызове.
// ---------------------------------------------------------------------------
template <typename It, typename Compare>
void insertionSort(It first, It last, Compare& comp) {
    // Тип элемента, на который «смотрит» итератор (для vector<int>::iterator это int).
    // typename нужен, потому что iterator_traits<It>::value_type зависит от шаблонного параметра,
    // и компилятору надо сказать: «это именно ТИП, а не переменная».
    using T = typename std::iterator_traits<It>::value_type;

    // Пустой диапазон: first + 1 был бы за пределами — выходим сразу.
    if (first == last) return;

    // Первый элемент (first) считаем «уже отсортированной частью из одного элемента»,
    // поэтому начинаем со второго.
    for (It i = first + 1; i != last; ++i) {
        // Вынимаем текущий элемент в локальную переменную.
        // std::move(*i) — «можно забрать содержимое *i, не копируя» (для int без разницы,
        // для тяжёлых типов — выигрыш).
        T key = std::move(*i);

        // j — «дырка», в которую в конце положим key. Сначала дырка на месте i.
        It j = i;

        // Пока слева ещё есть элементы (j != first) И key должен стоять СТРОГО раньше левого соседа,
        // сдвигаем соседа вправо в дырку, а дырка уходит влево.
        // Условие строгое (comp(key, left), а не «не больше») — поэтому равные элементы
        // не перескакивают друг через друга, и сортировка устойчивая.
        while (j != first && comp(key, *(j - 1))) {
            *j = std::move(*(j - 1));  // сдвиг соседа вправо
            --j;                       // дырка уехала влево
        }

        // Кладём key в найденную дырку.
        *j = std::move(key);
    }
}

// ---------------------------------------------------------------------------
// Слияние двух соседних отсортированных кусков [first, mid) и [mid, last)
// в один отсортированный [first, last).
// buf — указатель на временный буфер, в нём должно поместиться (mid - first) элементов.
// ---------------------------------------------------------------------------
template <typename It, typename T, typename Compare>
void mergeHalves(It first, It mid, It last, T* buf, Compare& comp) {
    // Быстрый выход: если первый элемент правой половины НЕ меньше последнего элемента левой,
    // то половины уже стоят в правильном порядке и сливать нечего.
    // На отсортированном входе это делает слияние почти бесплатным (O(1) вместо O(n)).
    if (!comp(*mid, *(mid - 1))) return;

    // Шаг 1. Копируем (точнее, перемещаем) ЛЕВУЮ половину во временный буфер.
    // bufEnd — указатель «за последним» элементом в буфере.
    T* bufEnd = buf;
    for (It p = first; p != mid; ++p, ++bufEnd) {
        *bufEnd = std::move(*p);
    }

    // Шаг 2. Сливаем: левая половина теперь лежит в буфере [buf, bufEnd),
    // правая всё ещё на месте [mid, last); пишем результат с позиции first.
    T* b = buf;       // текущий элемент левой половины (в буфере)
    It r = mid;       // текущий элемент правой половины (в исходном массиве)
    It out = first;   // куда писать следующий результат

    // Почему запись не затрёт ещё не прочитанные элементы правой половины?
    // Количество записанных элементов = (взято из левой) + (взято из правой) <= размер левой + (r - mid)
    // = (mid - first) + (r - mid) = r - first, то есть out никогда не обгоняет r.
    while (b != bufEnd && r != last) {
        if (comp(*r, *b)) {
            // Элемент справа СТРОГО меньше элемента слева — берём правый.
            *out = std::move(*r);
            ++r;
        } else {
            // Иначе (меньше слева ИЛИ равны) берём левый.
            // Взятие левого при равенстве — это и есть устойчивость.
            *out = std::move(*b);
            ++b;
        }
        ++out;
    }

    // Шаг 3. Если правая половина кончилась раньше, то остаток левой (в буфере) переносим в конец.
    // Если кончилась левая — остаток правой уже стоит на своих местах, ничего делать не надо.
    while (b != bufEnd) {
        *out = std::move(*b);
        ++b;
        ++out;
    }
}

// ---------------------------------------------------------------------------
// Рекурсивная часть: сортирует [first, last), используя буфер buf.
// ---------------------------------------------------------------------------
template <typename It, typename T, typename Compare>
void mergeSortImpl(It first, It last, T* buf, Compare& comp) {
    // Разность итераторов — «сколько элементов в диапазоне» (знаковое число).
    const auto n = last - first;

    // База рекурсии: кусок короткий — сортируем вставками и выходим.
    // Это же гарантирует, что при делении пополам обе половины непустые.
    if (n <= kInsertionCutoff) {
        insertionSort(first, last, comp);
        return;
    }

    // Середина диапазона. Левая половина: n/2 элементов, правая: n - n/2.
    It mid = first + n / 2;

    mergeSortImpl(first, mid, buf, comp);  // отсортировать левую половину
    mergeSortImpl(mid, last, buf, comp);   // отсортировать правую половину
    mergeHalves(first, mid, last, buf, comp);  // слить их
}

}  // namespace detail

// ===========================================================================
// ПУБЛИЧНАЯ ФУНКЦИЯ. Сигнатура — ровно из задания.
//
// template <typename It, typename Compare = ...> — «функция-шаблон»: компилятор сам сгенерирует
// свою версию для каждого сочетания типов (vector<int>::iterator, vector<Point>::iterator, int* ...).
// Compare по умолчанию — std::less<тип элемента>, то есть обычное «a < b».
// Для Point такого оператора нет, поэтому для Point компаратор надо передавать явно (ByDistance).
//
// [first, last) — полуинтервал: first указывает на первый элемент, last — на позицию ПОСЛЕ последнего.
// ===========================================================================
template <typename It, typename Compare = std::less<typename std::iterator_traits<It>::value_type>>
void mySort(It first, It last, Compare comp = Compare{}) {
    using T = typename std::iterator_traits<It>::value_type;

    // Сколько элементов сортируем.
    const auto n = last - first;

    // 0 или 1 элемент — уже отсортировано. Заодно защищает от создания буфера нулевого размера.
    if (n < 2) return;

    // Временный буфер для слияния. Нужен максимум n/2 элементов (размер левой половины на верхнем
    // уровне; на нижних уровнях куски меньше). Выделяем ОДИН раз на всю сортировку,
    // а не на каждое слияние — это заметно дешевле.
    // std::vector освобождает память сам при выходе из функции (RAII) — утечек нет.
    std::vector<T> buffer(static_cast<std::size_t>(n / 2));

    // buffer.data() — сырой указатель T* на начало памяти вектора.
    detail::mergeSortImpl(first, last, buffer.data(), comp);
}
