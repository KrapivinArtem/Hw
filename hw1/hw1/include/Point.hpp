// Point.hpp
// Точка на плоскости и компаратор «по расстоянию до начала координат».

#pragma once  // «Подключай этот файл не более одного раза за компиляцию» (защита от двойного #include).

// struct — это «класс, у которого всё публичное по умолчанию».
// Здесь это просто пара чисел, как кортеж (x, y) в Python.
// double — 64-битное число с плавающей точкой (аналог float в Python).
struct Point {
    double x, y;
};

// Оператор == нужен тестам: чтобы сравнивать два вектора точек (vector == vector),
// C++ должен уметь сравнивать две точки. Для struct он автоматически НЕ создаётся (до C++20).
//
// inline — потому что функция определена в заголовке, который подключают из нескольких .cpp;
//          без inline линковщик ругнулся бы на «множественное определение».
// const Point& — передача по константной ссылке: без копирования и без права менять аргумент.
inline bool operator==(const Point& a, const Point& b) {
    return a.x == b.x && a.y == b.y;
}

// Квадрат расстояния до начала координат (0, 0): x² + y².
inline double distSquared(const Point& p) {
    return p.x * p.x + p.y * p.y;
}

// Компаратор — «функциональный объект» (функтор): struct, у которого есть operator().
// Объект такого типа можно вызывать как функцию: ByDistance{}(a, b).
// Смысл: возвращает true, если a должна стоять СТРОГО раньше b (т.е. a ближе к началу координат).
//
// Почему сравниваем квадраты, а не сами расстояния?
// dist = sqrt(x² + y²), а sqrt — монотонно возрастающая функция на неотрицательных числах:
// если d1² < d2², то d1 < d2. Значит, порядок получается тот же, а дорогой sqrt не нужен.
//
// Последний const после списка параметров означает «этот метод не меняет сам объект».
// std::sort/mySort могут вызывать компаратор через константный объект, поэтому const важен.
struct ByDistance {
    bool operator()(const Point& a, const Point& b) const {
        return distSquared(a) < distSquared(b);
    }
};
